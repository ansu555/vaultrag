ARCH_NOTE = """# Architecture

```mermaid
flowchart TD
  A[Gateway Service] --> B[Event Store]
  B --> C[Nowhere Note]
```
"""
GATEWAY_NOTE = "# Gateway Service\n\nThe front door.\n"
STORE_NOTE = "# Event Store\n\nAppend-only log.\n"


def test_a_mermaid_edge_is_visible_through_related(  # type: ignore[no-untyped-def]
    tmp_path: Path, store, vector_store
) -> None:
    """The plan's acceptance criterion, end to end through the real pipeline."""
    vault = write_vault(
        tmp_path,
        {
            "architecture.md": ARCH_NOTE,
            "gateway-service.md": GATEWAY_NOTE,
            "event-store.md": STORE_NOTE,
        },
    )
    _reindex(vault, store, vector_store)

    doc_id = document_id(PROJECT, "architecture.md")
    edges = store.outgoing_links(PROJECT, doc_id)
    assert {e.kind for e in edges} == {"diagram"}

    notes, unresolved, _truncated = related_notes(
        project_id=PROJECT, doc_id=doc_id, store=store, hops=1
    )
    assert {n.path for n in notes} == {"gateway-service.md", "event-store.md"}
    assert all(n.relation == "links_to" for n in notes)
    # A node naming no document dangles rather than being dropped — the same honesty
    # `store/links.py` applies to a broken wikilink.
    assert unresolved == ["Nowhere Note"]


def test_a_diagram_edge_is_revoked_when_the_diagram_changes(  # type: ignore[no-untyped-def]
    tmp_path: Path, store, vector_store
) -> None:
    """Anchoring edges on the containing note is what makes this possible at all.

    `replace_links` replaces by `src_doc`; an edge sourced at some *other* document
    could never be revoked when this note's diagram is edited.
    """
    vault = write_vault(
        tmp_path,
        {
            "architecture.md": ARCH_NOTE,
            "gateway-service.md": GATEWAY_NOTE,
            "event-store.md": STORE_NOTE,
        },
    )
    _reindex(vault, store, vector_store)

    (vault / "architecture.md").write_text(
        "# Architecture\n\n```mermaid\nflowchart TD\n  A[Event Store] --> B[Elsewhere]\n```\n",
        encoding="utf-8",
    )
    _reindex(vault, store, vector_store)

    doc_id = document_id(PROJECT, "architecture.md")
    linked = {d.path for d in store.linked_docs(PROJECT, doc_id)}
    assert linked == {"event-store.md"}  # gateway edge is gone, not merely superseded


