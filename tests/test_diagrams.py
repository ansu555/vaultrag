"""P2 Stage 5 verify: Mermaid edges + Excalidraw scenes.

The plan's acceptance list, one test each:

* an Excalidraw file's labels/frame names are searchable;
* a ``compressed-json`` Excalidraw decompresses and indexes;
* a Mermaid ``A --> B`` produces a ``diagram`` edge visible through ``related``;
* non-flowchart Mermaid degrades to searchable-text-only without erroring.

Plus the two failure modes the stage introduces and must not ship: the base64 blob
reaching the index, and an existing index silently never gaining the new edges.

The ``compressed-json`` fixture is **generated by the JavaScript ``lz-string``** that
Obsidian's plugin actually uses, not by the Python port under test. A round-trip
through one library proves only that the library agrees with itself; this pins the
cross-implementation compatibility the whole Excalidraw path rests on.
"""

