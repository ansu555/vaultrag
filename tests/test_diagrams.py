def test_an_index_built_by_an_older_parser_is_reported_stale(  # type: ignore[no-untyped-def]
    tmp_path: Path, store, vector_store
) -> None:
    """The silent-green failure Stage 2 actually shipped, caught by construction here.

    An unchanged file is hash-equal, so the reconcile skips it — even though today's
    parser would now read Mermaid edges out of it. Nothing about the run looks wrong;
    the diagram graph is simply, permanently empty.
    """
    vault = write_vault(tmp_path, {"architecture.md": ARCH_NOTE})
    _reindex(vault, store, vector_store)
    store.set_parser_version(PROJECT, PARSER_VERSION - 1)  # simulate an older index

    stats = _reindex(vault, store, vector_store)

    assert stats.unchanged == 1  # nothing to do, as far as the manifest is concerned
    assert stats.stale_parser is True
    assert store.get_parser_version(PROJECT) == PARSER_VERSION - 1  # still not repaired


def test_a_forced_reindex_clears_the_stale_marker(  # type: ignore[no-untyped-def]
    tmp_path: Path, store, vector_store
) -> None:
    """`--force` is the documented repair, and only it may claim the index is current."""
    vault = write_vault(tmp_path, {"architecture.md": ARCH_NOTE})
    _reindex(vault, store, vector_store)
